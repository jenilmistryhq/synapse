export function exhibitIcon(name) {
  const s = document.createElement('span');
  s.className = 'ex-ic';
  s.setAttribute('aria-hidden', 'true');
  s.innerHTML = `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${EXHIBIT_ICONS[name] || EXHIBIT_ICONS.item}</svg>`;
  return s;
}

// The exhibits a player can see right now: those whose source is readable.
export const visibleExhibits = (m, ids) => (m.exhibits || []).filter(x => ids.includes(x.source));

// One sealed evidence bag. "big" is the version in the exhibit card.
export function evidenceBag(x, { big = false } = {}) {
  return h('span', { class: `bag${x.missing ? ' missing' : ''}${big ? ' big' : ''}` },
    h('span', { class: 'bag-zip' }),
    h('span', { class: 'bag-strip' }, x.missing ? 'Not recovered' : 'Evidence'),
    h('span', { class: 'bag-item' }, exhibitIcon(x.icon)),
    h('span', { class: 'bag-tag' }, h('b', {}, x.ref), h('span', {}, x.name)));
}
